"""Bootstrap confidence intervals for the runtime table.

Timing data is single-run per dataset, so the intervals are obtained by
bootstrapping across datasets.
"""
import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from _common import (  # noqa: E402
    CSV_DIR,
    DEFAULT_RESULTS,
    TABLES_DIR,
    ensure_results_dirs,
)

METHODS = [
    ("SHAP", "shap"),
    ("ExplainerPFN", "explainerpfn"),
    ("TabPFN", "tabpfn_n10"),
    ("MLP", "mlp_n10"),
    ("RF", "rfr_n10"),
]

def load_times(pickle_path):
    with open(pickle_path, "rb") as f:
        data = pickle.load(f)
    records = []
    for dataset_name, ds_data in data.items():
        X_train = np.asarray(ds_data["X_train"])
        X_test = np.asarray(ds_data["X_test"])
        n_cells = X_train.shape[1] * (X_train.shape[0] + X_test.shape[0])
        for label, key_prefix in METHODS:
            time_key = f"{key_prefix}_time"
            if time_key in ds_data and ds_data[time_key] is not None:
                records.append({
                    "dataset": dataset_name,
                    "method": label,
                    "time": 1000.0 * ds_data[time_key] / n_cells,
                })
    return pd.DataFrame(records)

def bootstrap_ci(values, n_bootstrap=1000, ci=0.95):
    rng = np.random.default_rng(42)
    boot_means = []
    for _ in range(n_bootstrap):
        sample = rng.choice(values, size=len(values), replace=True)
        boot_means.append(sample.mean())
    boot_means = np.array(boot_means)
    alpha = (1 - ci) / 2
    lower = np.percentile(boot_means, alpha * 100)
    upper = np.percentile(boot_means, 100 - alpha * 100)
    return values.mean(), lower, upper

def main():
    ensure_results_dirs()

    for base_model, pickle_name in [
        ("MLP", DEFAULT_RESULTS["mlp"]),
        ("Random Forest", DEFAULT_RESULTS["random_forest"]),
    ]:
        df = load_times(pickle_name)
        print(f"\n=== {base_model} ===")
        for method, _ in METHODS:
            sub = df[df["method"] == method]["time"].values
            if len(sub) == 0:
                continue
            mean, lower, upper = bootstrap_ci(sub)
            print(f"{method:15s}: {mean:.3f} [{lower:.3f}, {upper:.3f}]")

    # Also save to CSV for reference
    df_mlp = load_times(DEFAULT_RESULTS["mlp"])
    df_mlp["base_model"] = "MLP"
    df_rf = load_times(DEFAULT_RESULTS["random_forest"])
    df_rf["base_model"] = "Random Forest"
    df_all = pd.concat([df_mlp, df_rf], ignore_index=True)

    summary = []
    for base_model in ["MLP", "Random Forest"]:
        for method, _ in METHODS:
            sub = df_all[(df_all["base_model"] == base_model) & (df_all["method"] == method)]["time"].values
            if len(sub) == 0:
                continue
            mean, lower, upper = bootstrap_ci(sub)
            summary.append({
                "base_model": base_model,
                "method": method,
                "mean": mean,
                "lower": lower,
                "upper": upper,
            })

    df_summary = pd.DataFrame(summary)
    df_summary.to_csv(CSV_DIR / "runtime_bootstrap_cis.csv", index=False)
    print(f"\nSaved summary to {CSV_DIR / 'runtime_bootstrap_cis.csv'}")

    # Generate updated LaTeX table
    lines = []
    lines.append("% Generated by scripts/results/runtime_cis.py")
    lines.append("\\begin{tabular}{ccc}")
    lines.append("\\toprule")
    lines.append("   & \\multicolumn{2}{c}{Base Model}  \\\\")
    lines.append("  Method & MLP & RF \\\\")
    lines.append("  \\midrule")

    # Determine best/second-best per column for bold/underline
    mlp_vals = {}
    rf_vals = {}
    for _, row in df_summary.iterrows():
        if row["base_model"] == "MLP":
            mlp_vals[row["method"]] = row["mean"]
        else:
            rf_vals[row["method"]] = row["mean"]

    def format_cell(method, base_vals):
        mean = base_vals[method]["mean"]
        lower = base_vals[method]["lower"]
        upper = base_vals[method]["upper"]
        return f"{mean:.3f} ({lower:.3f}--{upper:.3f})"

    # Build per-method rows with formatting
    mlp_best = min(mlp_vals, key=mlp_vals.get)
    rf_best = min(rf_vals, key=rf_vals.get)
    mlp_sorted = sorted(mlp_vals.items(), key=lambda x: x[1])
    rf_sorted = sorted(rf_vals.items(), key=lambda x: x[1])
    mlp_second = mlp_sorted[1][0] if len(mlp_sorted) > 1 else None
    rf_second = rf_sorted[1][0] if len(rf_sorted) > 1 else None

    for method, _ in METHODS:
        mlp_row = df_summary[(df_summary["base_model"] == "MLP") & (df_summary["method"] == method)].iloc[0]
        rf_row = df_summary[(df_summary["base_model"] == "Random Forest") & (df_summary["method"] == method)].iloc[0]

        mlp_str = f"{mlp_row['mean']:.3f}"
        rf_str = f"{rf_row['mean']:.3f}"

        if method == mlp_best:
            mlp_str = f"\\textbf{{{mlp_str}}}"
        elif method == mlp_second:
            mlp_str = f"\\underline{{{mlp_str}}}"

        if method == rf_best:
            rf_str = f"\\textbf{{{rf_str}}}"
        elif method == rf_second:
            rf_str = f"\\underline{{{rf_str}}}"

        lines.append(f"  {method} & {mlp_str} & {rf_str} \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")

    tex_path = TABLES_DIR / "results_time_per_1000_cells.tex"
    with open(tex_path, "w") as f:
        f.write("\n".join(lines))
    print(f"Saved updated table to {tex_path}")

if __name__ == "__main__":
    main()
